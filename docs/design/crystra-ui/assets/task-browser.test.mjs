test('Task Browser: page-size picker opens above when footer has no room below', async () => {
 const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 try {
  const page=await browser.newPage({viewport:{width:1920,height:1080}});
  await page.goto(target,{waitUntil:'networkidle'});
  await page.locator('#browser-view-toggle-seat .wsr-toggle-switch').click();
  const select=page.locator('#browser-page-size');
  await select.scrollIntoViewIfNeeded();
  await select.click();
  const trigger=await select.boundingBox();
  const options=await select.locator('option').evaluateAll(els=>els.map(el=>{const r=el.getBoundingClientRect();return {top:r.top,bottom:r.bottom,height:r.height};}));
  assert.ok(options.every(r=>r.height>0&&r.top>=0&&r.bottom<=trigger.y),JSON.stringify({trigger,options}));
  await page.screenshot({path:new URL('./task-browser-page-size-menu.png',import.meta.url).pathname});
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  assert.equal(await select.inputValue(),'24');
  assert.equal(await page.locator('[data-list-task]').count(),24);
  await page.locator('#browser-search').fill('UI 工作台设计');
  await select.click();
  const upperTrigger=await select.boundingBox();
  const firstOption=await select.locator('option').first().boundingBox();
  assert.ok(firstOption.y>=upperTrigger.y+upperTrigger.height);
  await page.keyboard.press('Escape');
 } finally {await browser.close();}
});
